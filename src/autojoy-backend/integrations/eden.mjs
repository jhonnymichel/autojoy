import path from "path";
import { loaders, savers } from "../../common/file.mjs";
import { user } from "../../common/settings.mjs";

const configTemplates = loaders.ini("config-templates/eden.ini");
const configFile = path.resolve(
  user.paths.eden,
  "user",
  "config",
  "qt-config.ini",
);
const playerIdentifiers = [
  "player_0_",
  "player_1_",
  "player_2_",
  "player_3_",
  "player_4_",
  "player_5_",
  "player_6_",
  "player_7_",
];
const playerIdentifierRegex = /player_\d_/;
const controllerGuidIdenifierRegex = /guid:.+,/;

function getJoystickSubtype(joystick) {
  const joystickName = joystick.name.toLowerCase();

  const consoleControllerNames = [
    "ps",
    "playstation",
    "play station",
    "nintendo switch",
    "switch",
  ];

  if (
    consoleControllerNames.some((consoleControllerName) =>
      joystickName.includes(consoleControllerName),
    )
  ) {
    return "consolecontroller";
  }

  return "xinput";
}

function getJoystickGUID(joystick) {
  return (
    joystick.raw.guid.substring(0, 2) +
    "000000" +
    joystick.raw.guid.substring(8)
  );
}

function handleJoystickListUpdate(joystickList) {
  let newConfig;
  try {
    newConfig = loaders.ini(configFile);
  } catch (e) {
    newConfig = {};
  }

  playerIdentifiers.forEach((identifier, position) => {
    const joystick = joystickList[position];

    if (!joystick) {
      newConfig[`${identifier}connected`] = false;
      return;
    }

    const joystickSubtype = getJoystickSubtype(joystick);
    const joystickGUID = getJoystickGUID(joystick);

    const config = structuredClone(
      configTemplates[`${joystick.type}.${joystickSubtype}`] ?? {},
    );

    Object.entries(config).forEach(([key, value]) => {
      newConfig[key.replace(playerIdentifierRegex, identifier)] = value.replace(
        controllerGuidIdenifierRegex,
        `guid:${joystickGUID}`,
      );
    });
  });

  savers.ini(newConfig, path.resolve(configFile));
  console.log("Eden - Input settings saved at", configFile);
}

const eden = { handleJoystickListUpdate };
export default eden;
